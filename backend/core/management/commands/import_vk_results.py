class Command(BaseCommand):
    help = "Импорт исторических матчей из сеток VK"

    def add_arguments(self, parser):
        parser.add_argument("--apply", action="store_true", help="Записать в БД")

    def handle(self, *args, **options):
        apply_changes = options["apply"]
        tz = timezone.get_current_timezone()

        for item in TOURNAMENTS:
            if item.get("tournament_id"):
                tournament = Tournament.objects.filter(
                    pk=item["tournament_id"]
                ).first()
            else:
                tournament = Tournament.objects.filter(
                    source_url=item["source_url"]
                ).first()
            if not tournament:
                raise CommandError(
                    f"Турнир не найден по source_url {item['source_url']}"
                )
            cancelled = Match.objects.filter(
                tournament=tournament, winner__isnull=True
            ).count()
            self.stdout.write(
                f"{tournament.name}: матчей {len(item['matches'])}, "
                f"без победителя {cancelled}"
            )

            if not apply_changes:
                continue

            with transaction.atomic():
                Match.objects.filter(
                    tournament=tournament, is_historical=True
                ).delete()

                slot_by_round = {}
                first_slots = item.get("first_round_slots")
                consolation_first_slots = item.get("consolation_first_slots")
                for index, (round_no, bracket, group, p1, p2, score, winner_side) in enumerate(
                    item["matches"], start=1
                ):
                    slot = slot_by_round.get((bracket, round_no), 0)
                    slot_by_round[(bracket, round_no)] = slot + 1
                    slot_index = slot
                    if bracket == "winners" and round_no == 1 and first_slots:
                        if slot < len(first_slots):
                            slot_index = first_slots[slot]
                    elif bracket == "consolation" and round_no == 1 and consolation_first_slots:
                        if slot < len(consolation_first_slots):
                            slot_index = consolation_first_slots[slot]
                    side1 = [self._player(name) for name in p1]
                    side2 = [self._player(name) for name in p2]
                    winner = side1[0] if winner_side == 1 else side2[0]
                    Match.objects.create(
                        tournament=tournament,
                        gender_type=tournament.gender_type,
                        bracket=bracket,
                        group=group,
                        round_number=round_no,
                        slot_index=slot_index,
                        player1=side1[0],
                        pair1_player2=side1[1] if len(side1) > 1 else None,
                        player2=side2[0],
                        pair2_player2=side2[1] if len(side2) > 1 else None,
                        winner=winner,
                        status=Match.Status.FINISHED,
                        score=score,
                        is_historical=True,
                        scheduled_at=timezone.make_aware(
                            datetime.combine(tournament.start_date, time(10, 0)), tz
                        ),
                    )

                for seed, name in item.get("participants", []):
                    player = self._player(name)
                    registration, created = TournamentRegistration.objects.get_or_create(
                        tournament=tournament,
                        player=player,
                        defaults={
                            "status": TournamentRegistration.Status.APPROVED,
                            "seed": seed,
                        },
                    )
                    if not created and registration.seed != seed:
                        registration.seed = seed
                        registration.save(update_fields=["seed"])

                for pair_id, (seed, names) in enumerate(item.get("pairs", []), start=1):
                    for name in names:
                        player = self._player(name)
                        registration, created = TournamentRegistration.objects.get_or_create(
                            tournament=tournament,
                            player=player,
                            defaults={
                                "status": TournamentRegistration.Status.APPROVED,
                                "seed": seed,
                                "pair_id": pair_id,
                            },
                        )
                        if not created and (
                            registration.seed != seed or registration.pair_id != pair_id
                        ):
                            registration.seed = seed
                            registration.pair_id = pair_id
                            registration.save(update_fields=["seed", "pair_id"])

                points_table = item.get("points_table")
                if points_table is not None:
                    tournament.points_table = points_table
                    if item.get("points_category") is not None:
                        tournament.points_category = item["points_category"]
                    else:
                        tournament.points_category = "two_day" if points_table else ""
                    tournament.save(update_fields=["points_table", "points_category"])
                if item.get("format"):
                    Tournament.objects.filter(pk=tournament.pk).update(
                        format=item["format"]
                    )
            self.stdout.write(self.style.SUCCESS("  импортировано"))

    @staticmethod
    def _player(name):
        name = ALIASES.get(name, name)
        last_name, first_name = split_name(name)
        player = (
            Player.objects
            .filter(last_name__iexact=last_name, first_name__iexact=first_name)
            .first()
        )
        if player:
            return player

        base = f"vk-{translit(last_name)}-{translit(first_name)}".strip("-")
        email = f"{base}@tennis.local"
        suffix = 1
        while Player.objects.filter(email=email).exists():
            suffix += 1
            email = f"{base}-{suffix}@tennis.local"
        return Player.objects.create(
            first_name=first_name,
            last_name=last_name,
            email=email,
            gender="female",
        )
