def translit(value):
    return "".join(TRANSLIT.get(char, char) for char in value.lower())


def split_name(value):
    value = re.sub(r"\s+", " ", value.replace("ё", "е")).strip(" .,")
    parts = [part for part in value.split(" ") if part]
    if len(parts) >= 2:
        return parts[0], " ".join(parts[1:])
    return value, ""


